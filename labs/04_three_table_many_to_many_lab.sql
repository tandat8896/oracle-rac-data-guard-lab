create table dm_customers (
  id          number generated by default as identity,
  full_name   varchar2(100) not null,
  email       varchar2(200) not null,
  created_at  timestamp default systimestamp not null,
  constraint pk_dm_customers primary key (id),
  constraint uq_dm_customers_email unique (email)
);

create table dm_accounts (
  id          number generated by default as identity,
  acct_no     varchar2(30) not null,
  acct_type   varchar2(20) not null,
  status      varchar2(20) default 'ACTIVE' not null,
  created_at  timestamp default systimestamp not null,
  constraint pk_dm_accounts primary key (id),
  constraint uq_dm_accounts_acct_no unique (acct_no),
  constraint ck_dm_accounts_type check (acct_type in ('SAVINGS', 'CHECKING')),
  constraint ck_dm_accounts_status check (status in ('ACTIVE', 'CLOSED'))
);

create table dm_account_customers (
  account_id   number not null,
  customer_id  number not null,
  role_name    varchar2(30) default 'OWNER' not null,
  linked_at    timestamp default systimestamp not null,
  constraint pk_dm_account_customers primary key (account_id, customer_id),
  constraint fk_dm_acctcust_account foreign key (account_id)
    references dm_accounts(id),
  constraint fk_dm_acctcust_customer foreign key (customer_id)
    references dm_customers(id),
  constraint ck_dm_acctcust_role check (role_name in ('OWNER', 'CO_OWNER', 'AUTHORIZED_USER'))
);

create index ix_dm_acctcust_customer
  on dm_account_customers(customer_id);

