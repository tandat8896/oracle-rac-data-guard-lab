select c.table_name as child_table,
       cc.column_name as child_column,
       p.table_name as parent_table,
       pc.column_name as parent_column
from user_constraints c
join user_cons_columns cc
  on cc.constraint_name = c.constraint_name
 and cc.table_name = c.table_name
join user_constraints p
  on p.constraint_name = c.r_constraint_name
join user_cons_columns pc
  on pc.constraint_name = p.constraint_name
 and pc.position = cc.position
where c.constraint_type = 'R'
  and c.table_name like 'DM\_%' escape '\'
order by c.table_name, cc.position;

with fk_cols as (
  select c.table_name,
         c.constraint_name,
         cc.column_name,
         cc.position
  from user_constraints c
  join user_cons_columns cc
    on cc.constraint_name = c.constraint_name
   and cc.table_name = c.table_name
  where c.constraint_type = 'R'
    and c.table_name like 'DM\_%' escape '\'
),
fk_summary as (
  select table_name,
         count(distinct constraint_name) as fk_count,
         count(*) as fk_col_count,
         listagg(column_name, ', ') within group (order by column_name) as fk_columns_sorted
  from fk_cols
  group by table_name
),
key_cols as (
  select c.table_name,
         c.constraint_type,
         c.constraint_name,
         cc.column_name
  from user_constraints c
  join user_cons_columns cc
    on cc.constraint_name = c.constraint_name
   and cc.table_name = c.table_name
  where c.constraint_type in ('P', 'U')
    and c.table_name like 'DM\_%' escape '\'
),
key_summary as (
  select table_name,
         constraint_type,
         constraint_name,
         listagg(column_name, ', ') within group (order by column_name) as key_columns_sorted
  from key_cols
  group by table_name, constraint_type, constraint_name
),
col_summary as (
  select table_name,
         count(*) as total_columns
  from user_tab_columns
  where table_name like 'DM\_%' escape '\'
  group by table_name
)
select f.table_name,
       f.fk_count,
       f.fk_columns_sorted,
       k.constraint_type as matching_key_type,
       k.key_columns_sorted,
       col.total_columns,
       (col.total_columns - f.fk_col_count) as non_fk_columns,
       case
         when k.key_columns_sorted = f.fk_columns_sorted
              and (col.total_columns - f.fk_col_count) <= 3
         then 'LIKELY_MANY_TO_MANY_BRIDGE'
         when f.fk_count >= 2
         then 'POSSIBLE_BRIDGE_OR_BUSINESS_ENTITY'
       end as classification
from fk_summary f
join col_summary col
  on col.table_name = f.table_name
left join key_summary k
  on k.table_name = f.table_name
 and k.key_columns_sorted = f.fk_columns_sorted
where f.fk_count >= 2
order by classification, f.table_name;
